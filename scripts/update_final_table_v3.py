"""최종_이동취약지대.csv 갱신: 접근성 지수를 v3(고령인구당 버스정류소 반영)로 교체.

- 접근성지수/접근성순위/접근성_하위%/접근성_판정을 v3 기준으로 교체, 기존(v1) 지수는 접근성지수_v1로 보존
- 고령인구_추정, 고령1천명당_정류소 컬럼 추가(신월2동 확정 이동 사유의 근거 수치)
- 신월2동: 참고 -> 확정 (사유: 고령인구당 버스정류소 2.8, 9곳 중 최저 - 지하철은 가까우나 버스가 고령인구 대비 부족)
- 방화2동: 비고에 면적 영향 각주를 단다.
- 최종 구성: 확정 8곳(독산2동, 신월1동, 신월7동, 시흥4동, 시흥3동, 방화2동, 시흥5동, 신월2동) + 참고 1곳(시흥1동)
"""
import pandas as pd

OUT = "data/interim/재현확인/최종_이동취약지대.csv"
CONFIRMED = ["독산2동", "신월1동", "신월7동", "시흥4동", "시흥3동", "방화2동", "시흥5동", "신월2동"]
REFERENCE = ["시흥1동"]

t = pd.read_csv(OUT, encoding="utf-8-sig", dtype={"경계코드": str})
v3 = pd.read_csv("data/interim/재현확인/접근성_9곳_v3.csv", encoding="utf-8-sig")[
    ["동이름", "지수_v3", "하위%_v3", "순위_v3", "분류_v3"]]
comp = pd.read_csv("data/raw/접근성_9곳_v3_구성요소.csv", encoding="utf-8-sig")[["동이름", "고령1천명당_정류소"]]
eld = pd.read_csv("data/interim/재현확인/행정동별_고령인구.csv", encoding="utf-8-sig", dtype={"경계코드": str})[["경계코드", "고령인구_추정"]]

assert set(t["동이름"]) == set(CONFIRMED + REFERENCE) == set(v3["동이름"])
t = t.rename(columns={"접근성지수": "접근성지수_v1"}).drop(columns=["접근성순위", "접근성_하위%", "접근성_판정"])
t = t.merge(v3, on="동이름").merge(comp, on="동이름").merge(eld, on="경계코드")
t = t.rename(columns={"지수_v3": "접근성지수", "순위_v3": "접근성순위", "하위%_v3": "접근성_하위%"})

def judge(pct):
    if pct <= 10:
        return "하위 10% (인프라 매우 부족)"
    if pct <= 25:
        return "하위 25% (인프라 부족)"
    if pct <= 50:
        return "하위 50% (하위권 아님, 중간 이하)"
    return "중간 이상"
t["접근성_판정"] = t["접근성_하위%"].map(judge)

t["구분"] = t["동이름"].map(lambda n: "확정" if n in CONFIRMED else "참고")
BASE_CONF = "접근성 하위 25% 이내(v3, 고령인구당 버스정류소 반영) + 차량의존 + 소득 낮음(<=6분위)"
BASE_REF = "접근성 하위권 밖(v3 기준도 동일), 추가조사 보류"
t["비고"] = t["구분"].map({"확정": BASE_CONF, "참고": BASE_REF})
t.loc[t["동이름"] == "신월2동", "비고"] = (
    BASE_CONF + " | 참고→확정 이동(2026-09-22): 고령인구당 버스정류소 2.8개/천명으로 9곳 중 최저"
    "(지하철 최단거리 690m로 가까우나 고령인구 대비 버스가 부족한 것이 원인으로 확인됨)")
t.loc[t["동이름"] == "방화2동", "비고"] = (
    BASE_CONF + " | 버스밀도 지표가 넓은 면적(6.15km², 서울 중앙값의 약 6배) 영향을 받았을 가능성 있음"
    "(고령인구당 정류소는 서울 평균 이상: 백분위 54.8)")

t["구분_순서"] = t["구분"].map({"확정": 0, "참고": 1})
t = t.sort_values(["구분_순서", "접근성지수"]).drop(columns="구분_순서")

cols = ["구분", "동이름", "자치구", "경계코드", "우선순위_순위", "우선순위점수", "차량비율", "버스비율", "지하철비율", "도보비율",
        "대중교통비율(버스+지하철)", "귀가시간대고령층합계", "귀가비중", "소득분위", "가구수", "소득구분",
        "접근성지수", "접근성지수_v1", "접근성순위", "접근성_하위%", "접근성_판정",
        "고령인구_추정", "고령1천명당_정류소", "버스정류소수", "버스정류소밀도_개per_km2", "마을버스제외밀도",
        "지하철최단거리_m", "최근접역", "지하철역수_1km", "면적_km2", "x_5179", "y_5179", "경도_WGS84", "위도_WGS84",
        "중심점방식", "비고"]
t = t[cols]
t.to_csv(OUT, index=False, encoding="utf-8-sig")

pd.set_option("display.width", 250)
print(f"저장: {OUT} ({len(t)}행 x {len(t.columns)}열)  확정 {int((t['구분'] == '확정').sum())} / 참고 {int((t['구분'] == '참고').sum())}")
print(t[["구분", "자치구", "동이름", "접근성지수", "접근성지수_v1", "접근성_하위%", "고령1천명당_정류소", "접근성_판정"]].to_string(index=False))
print("\n방화2동 비고:", t.loc[t["동이름"] == "방화2동", "비고"].iloc[0])
print("신월2동 비고:", t.loc[t["동이름"] == "신월2동", "비고"].iloc[0])
